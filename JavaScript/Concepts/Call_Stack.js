// The call stack is a data structure used by the JavaScript engine to keep track of function calls — what's currently running and what should run next.

// It follows the LIFO (Last In, First Out) principle:

// The last function called is the first to finish.

// How it works:
// When a function is invoked, it’s pushed onto the stack.

// When the function returns, it’s popped off the stack.

// The JS engine always executes the top function in the stack.